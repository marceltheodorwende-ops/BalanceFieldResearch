HERE=Path(__file__).resolve().parent
u,A,B,R=s.symbols('u A B R',positive=True)
ratio=(1+B*u)/(1+A*u);inverse=(R-1)/(B-A*R)
identities=[]
def exact(name,expr):
    assert s.simplify(expr)==0,(name,expr)
    identities.append(name)
exact('magnitude inverse',inverse.subs(R,ratio)-u)
exact('ratio monotonic derivative',s.diff(ratio,u)-(B-A)/(1+A*u)**2)
exact('inverse derivative',s.diff(inverse,R)-(B-A)/(B-A*R)**2)
w,t,a,d=s.symbols('omega theta gain delay',real=True)
H=a*s.exp(-s.I*w*d)/(1+s.I*w*t)
exact('delay corrected phase',H*(1+s.I*w*t)-a*s.exp(-s.I*w*d))
ss,b,w1,w2=s.symbols('s b w1 w2',real=True)
P=ss*(ss**2+w1**2)*(ss**2+w2**2)/(ss+b)**6
for label,node in [('DC',0),('first tone',s.I*w1),('second tone',s.I*w2)]:
    exact('stable rival zero '+label,P.subs(ss,node))
clock=s.symbols('time',real=True);output=s.Function('x')(clock)
theta,gain,offset=s.symbols('theta gain offset',real=True)
reconstructed=(output-offset+theta*s.diff(output,clock))/gain
exact('ideal reconstructed velocity',s.diff(reconstructed,clock)-
      (s.diff(output,clock)+theta*s.diff(output,clock,2))/gain)

def transfer(w,theta,gain,delay):return gain*np.exp(-1j*w*delay)/(1+1j*w*theta)
def recover(H1,H2,w1,w2):
    ratio=abs(H1)**2/abs(H2)**2
    u=(ratio-1)/(w2*w2-ratio*w1*w1)
    assert u>=-1e-12
    theta=np.sqrt(max(0,u));gain=abs(H1)*np.sqrt(1+w1*w1*theta*theta)
    U=H1/abs(H1)*(1+1j*w1*theta)/np.sqrt(1+w1*w1*theta*theta)
    delay=-np.angle(U)/w1
    return np.array([theta,gain,delay])
def interval(m1,m2,e1,e2,w1,w2):
    assert m1>e1 and m2>e2
    low=(m1-e1)**2/(m2+e2)**2;high=(m1+e1)**2/(m2-e2)**2
    lim=w2*w2/(w1*w1)
    if high<1 or low>=lim:return None
    low=max(1,low)
    lo=np.sqrt((low-1)/(w2*w2-low*w1*w1))
    hi=float('inf') if high>=lim else np.sqrt((high-1)/(w2*w2-high*w1*w1))
    return float(lo),float(hi)

cases=[]
for theta,gain,delay,w1,w2 in [(0.,1.2,.05,2.,5.),(.03,.8,.02,2.,5.),
                              (.12,1.3,.1,5.,11.),(10.,1.,.03,2.,5.)]:
    measured=[];dc=gain*.2+.02;reference=.4-.1j
    for omega in [w1,w2]:
        h=transfer(omega,theta,gain,delay)
        times=np.linspace(0,4*np.pi/omega,257)
        if theta==0:
            output=dc+gain*np.real(reference*np.exp(1j*omega*(times-delay)))
        else:
            def rhs(t,z):
                true=.2+np.real(reference*np.exp(1j*omega*(t-delay)))
                return [(gain*true+.02-z[0])/theta]
            sol=solve_ivp(rhs,[0,times[-1]],[dc+np.real(h*reference)],
                          t_eval=times,method='DOP853',rtol=2e-12,atol=2e-14)
            assert sol.success
            output=sol.y[0]
        design=np.column_stack([np.ones(len(times)),np.cos(omega*times),np.sin(omega*times)])
        c=np.linalg.lstsq(design,output,rcond=None)[0]
        measured.append((c[1]-1j*c[2])/reference)
    estimate=recover(*measured,w1,w2)
    error=float(np.max(abs(estimate-[theta,gain,delay])))
    assert error<2e-7
    cases.append(dict(theta=theta,gain=gain,delay=delay,frequencies=[w1,w2],
                      recovered=estimate.tolist(),independent_ode_inverse_error=error))

rng=np.random.default_rng(71);noise=[]
for theta,w1,w2 in [(.03,2.,5.),(.12,5.,11.),(10.,2.,5.)]:
    h1=transfer(w1,theta,1.,.05);h2=transfer(w2,theta,1.,.05)
    eps=1e-5*min(abs(h1),abs(h2));width=[];unbounded=0
    for _ in range(100):
        z1=h1+eps*rng.uniform(0,1)*np.exp(1j*rng.uniform(-np.pi,np.pi))
        z2=h2+eps*rng.uniform(0,1)*np.exp(1j*rng.uniform(-np.pi,np.pi))
        bounds=interval(abs(z1),abs(z2),eps,eps,w1,w2)
        assert bounds is not None
        assert bounds[0]-1e-9<=theta<=bounds[1]+1e-9
        if np.isfinite(bounds[1]):width.append(bounds[1]-bounds[0])
        else:unbounded+=1
    noise.append(dict(theta=theta,error_radius=eps,checks=100,
                      maximum_finite_interval_width=max(width) if width else None,
                      unbounded_intervals=unbounded))
assert interval(.5,1.,0,0,2.,5.) is None
assert interval(2.5,1.,.01,.01,2.,5.)[1]==float('inf')
